// Deliberate owner clipboard disclosure. The Rust app supplies a value only after
// a fresh item/field/revision check. No value is returned, logged, or persisted.
// Privacy markers are advisory; another local app can read or retain the text.

import AppKit
import Foundation

private let clipboardOwnerType = NSPasteboard.PasteboardType("com.wydrox.apassy.copy-owner")
private let clipboardMarkers = [
    NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
    NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
    NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
]
private let clipboardRemoteType = NSPasteboard.PasteboardType("com.apple.is-remote-clipboard")

func handleClipboardWrite(_ request: Request) throws -> Fields {
    // This command runs synchronously on the helper's main thread. The common
    // caller check ran before dispatch; no other process can request a copy here.
    guard Thread.isMainThread else {
        throw HelperError(.internalError, "The clipboard is unavailable.")
    }
    guard var bytes = Data(base64Encoded: try request.string("secret_b64")),
        bytes.count <= 65_536
    else {
        throw HelperError(.invalidRequest, "The clipboard value is invalid.")
    }
    defer { bytes.resetBytes(in: 0..<bytes.count) }
    guard let text = String(data: bytes, encoding: .utf8) else {
        throw HelperError(.invalidRequest, "The clipboard value is invalid.")
    }
    let owner = try request.identifier("owner")
    let item = NSPasteboardItem()
    guard item.setString(text, forType: .string),
        item.setString(owner, forType: clipboardOwnerType)
    else {
        throw HelperError(.failed, "The clipboard write failed.")
    }
    for marker in clipboardMarkers {
        guard item.setData(Data(), forType: marker) else {
            throw HelperError(.failed, "The clipboard privacy markers failed.")
        }
    }
    // The remote clipboard marker suppresses Universal Clipboard publication.
    guard item.setString("1", forType: clipboardRemoteType) else {
        throw HelperError(.failed, "The clipboard privacy markers failed.")
    }
    let board = NSPasteboard.general
    board.clearContents()
    guard board.writeObjects([item]) else {
        throw HelperError(.failed, "The clipboard write failed.")
    }
    let count = board.changeCount
    // A concurrent writer must not become the identity acknowledged as ours.
    guard board.string(forType: clipboardOwnerType) == owner,
        board.changeCount == count
    else {
        throw HelperError(.failed, "The clipboard changed during the write.")
    }
    return ["change_count": count, "owner": owner]
}

func handleClipboardClear(_ request: Request) throws -> Fields {
    guard Thread.isMainThread else {
        throw HelperError(.internalError, "The clipboard is unavailable.")
    }
    let owner = try request.identifier("owner")
    let expected: Int?
    if let raw = request.fields["change_count"] {
        guard let number = raw as? NSNumber,
            CFGetTypeID(number) != CFBooleanGetTypeID(),
            number.doubleValue.rounded() == number.doubleValue,
            number.doubleValue >= 0,
            number.doubleValue < Double(Int.max)
        else {
            throw HelperError(.invalidRequest, "The clipboard identity is invalid.")
        }
        expected = number.intValue
    } else {
        // Cleanup after a lost write acknowledgement: the caller supplied the
        // random owner marker before writing and cannot know the returned count.
        expected = nil
    }
    let board = NSPasteboard.general
    // Never compare clipboard text. A later copy of identical text is a different
    // write. NSPasteboard offers no interprocess compare-and-clear primitive;
    // these adjacent calls keep the unavoidable final race as small as possible.
    let count = board.changeCount
    if expected.map({ $0 == count }) ?? true,
        board.string(forType: clipboardOwnerType) == owner,
        board.changeCount == count
    {
        board.clearContents()
    }
    return [:]
}
