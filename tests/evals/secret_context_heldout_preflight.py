"""Candidate-free H2 pre-seal checks; synthetic data, procedural independence only.

This source was prepared before H2 existed. Its author must never open H2, H1,
weights, freezes or predictions. Future CI may read H2 using this program. No
candidate is loaded; passing is NOT quality evidence. A separate blind judge must
check command/request service and action, including the textual rule-2 clause.
Compiled Rust replay is mandatory before sealing; missing diagnostics fail closed.
Natural text is never shortened. Feedback contains counts and bounded IDs only.

API: preflight(rows, c, g1_rows, replay_binary=None). g1_rows is a mapping with
train/val lists regenerated by context_data.generate(7, 400/100, split); both
canonical JSONL hashes are verified BEFORE overlap. No historical artifacts used.

CLI: --data H2.jsonl --manifest H2.manifest.json --out NEW.json
     [--replay-binary PATH]. Exit 0 means machine checks complete, 1 means failure.
Manifest (exact keys): {"sha256": LOWERCASE64HEX, "generator": RELATIVE_PY_PATH,
"generator_sha256": LOWERCASE64HEX, "rubric": "secret-context-rubric-v1",
"counts": {"rows": N, "allow_ok": N, "must_ask": N, "deterministic_ask": N}}.
Generator is resolved relative to manifest, hashed only, never imported/executed.
No file key. Output must be a new file; input/source overwrites are impossible.
"""
